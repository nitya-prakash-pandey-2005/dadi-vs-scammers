"""Complaint draft for cybercrime.gov.in / 1930 / Sanchar Saathi Chakshu."""

from __future__ import annotations

from datetime import datetime, timezone

from voice_core.types import Turn

from .intel import ID_FIELDS, IntelReport
from .personas import FAMILY, HANDOFF_LINES, PERSONAS
from .taxonomy import RED_FLAG_LABELS, SCAM_TYPE_LABELS

DISCLAIMER = ("Simulated scam call: scammer played by an actor or our AI. Draft generated by Dadi vs Scammers "
              "for demonstration; review before filing.")
WHERE = ["cybercrime.gov.in", "Helpline 1930", "Sanchar Saathi – Chakshu (sancharsaathi.gov.in)"]


CHAKSHU_CATEGORY = {  # suggested Chakshu category per scam type (the reporter picks the final one)
    "digital_arrest": "Impersonation as Government official / Police",
    "courier_parcel": "Impersonation as Government official / Police",
    "kyc_bank_block": "KYC update of bank / electricity / gas / insurance",
    "electricity_bill": "KYC update of bank / electricity / gas / insurance",
    "lottery_prize": "Online job / lottery / gift / loan offers",
    "job_task": "Online job / lottery / gift / loan offers",
    "investment": "Illegal loan / financial fraud",
}


def _mmss(sec: float) -> str:
    sec = int(round(sec))
    return f"{sec // 60}:{sec % 60:02d}"


def build_report(call: dict, turns: list[Turn], intel: IntelReport) -> dict:
    started = float(call.get("started_at") or 0)
    ended = float(call.get("ended_at") or started)
    duration = ended - started
    persona = PERSONAS.get(call.get("persona") or "dadi", PERSONAS["dadi"])
    label = SCAM_TYPE_LABELS.get(intel.scam_type, "Other")
    ids = {k: getattr(intel, k) for k in ID_FIELDS if getattr(intel, k)}
    who = ", ".join(intel.agencies_claimed) or "an unknown organisation"
    names = f" (name given: {', '.join(intel.names)})" if intel.names else ""
    id_text = "; ".join(f"{k}: {', '.join(v)}" for k, v in ids.items()) or "none yet"
    # the family hand-off line is fixed text (personas.HANDOFF_LINES), so the transcript shows whether it happened
    relative = FAMILY.get(persona.key)
    handoff = relative is not None and any(HANDOFF_LINES[0][1] in t.text for t in turns if t.speaker != "scammer")
    decoy = f"decoys '{persona.name}' and her grandson '{relative.name}'" if handoff else f"decoy '{persona.name}'"
    summary = (
        f"A caller claiming to be from {who}{names} attempted a '{label}' scam. The AI {decoy} kept the "
        f"caller engaged for {_mmss(duration)} (time the scammer could not spend on a real victim). "
        f"Identifiers the caller revealed: {id_text}."
    )
    return {
        "title": "Suspected scam call: complaint draft",
        "disclaimer": DISCLAIMER,
        "call_id": call.get("id"),
        "persona": persona.name,
        "decoys": [persona.name, relative.name] if handoff else [persona.name],
        "summary": summary,
        "incident_time": datetime.fromtimestamp(started, tz=timezone.utc).isoformat() if started else None,
        "duration_seconds": duration,
        "scam_type": intel.scam_type,
        "scam_type_label": label,
        "scam_confidence": intel.scam_confidence,
        "claimed_identity": {"names": intel.names, "agencies": intel.agencies_claimed},
        "suspect_identifiers": ids,
        "amounts_demanded": intel.amounts,
        "red_flags": [
            {"flag": f.flag, "label": RED_FLAG_LABELS.get(f.flag, f.flag), "quote": f.quote, "t": f.t}
            for f in sorted(intel.red_flags, key=lambda f: f.t)
        ],
        "transcript_excerpt": [{"speaker": t.speaker, "text": t.text, "t": t.t} for t in turns[:12]],
        "where_to_report": WHERE,
        "chakshu": {
            "medium": "Call",
            "category": CHAKSHU_CATEGORY.get(intel.scam_type, "Others"),
            "date_time": datetime.fromtimestamp(started, tz=timezone.utc).isoformat() if started else None,
            "description": summary[:1000],
        },
    }
